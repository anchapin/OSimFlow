class TestServeKeysFileMode:
    """Mode 3 — multi-user mode via ``--api-keys-file``: no auto-gen, no notice."""

    def test_keys_file_skips_autogen(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """When --api-keys-file is set, create_app receives None as api_key and no banner prints."""
        keys_file = tmp_path / "api_keys.json"
        keys_file.write_text(
            '{"users": [{"key": "k", "user_id": "u", "role": "admin"}]}'
        )
        parser = _build_parser()
        args = parser.parse_args(
            [
                "serve",
                "--outdir",
                str(tmp_path),
                "--api-keys-file",
                str(keys_file),
            ]
        )
        mock_app, _ = _patched_serve(monkeypatch, tmp_path, args)
        with patch("osimflow.api.create_app", return_value=mock_app) as mock_create:
            result = _cmd_serve(args)

        assert result == 0
        # Multi-user mode: api_key is None, api_keys_file is forwarded.
        assert mock_create.call_args[1]["api_key"] is None
        assert mock_create.call_args[1]["api_keys_file"] == keys_file
        captured = capsys.readouterr()
        assert "Generated ephemeral API key" not in captured.err
        assert "Generated ephemeral API key" not in captured.out

    def test_keys_file_with_explicit_key_warns(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
    ) -> None:
        """Passing --api-key alongside --api-keys-file still warns + ignores the key."""
        keys_file = tmp_path / "api_keys.json"
        keys_file.write_text(
            '{"users": [{"key": "k", "user_id": "u", "role": "admin"}]}'
        )
        parser = _build_parser()
        args = parser.parse_args(
            [
                "serve",
                "--outdir",
                str(tmp_path),
                "--api-keys-file",
                str(keys_file),
                "--api-key",
                "ignored-because-keys-file-set",
            ]
        )
        mock_app, _ = _patched_serve(monkeypatch, tmp_path, args)
        with patch("osimflow.api.create_app", return_value=mock_app) as mock_create:
            with caplog.at_level(logging.WARNING, logger="osimflow.__main__"):
                result = _cmd_serve(args)

        assert result == 0
        assert mock_create.call_args[1]["api_key"] is None
        # The pre-existing "ignored" warning must still fire.
        ignored = [
            r for r in caplog.records if "--api-key is ignored" in r.getMessage()
        ]
        assert len(ignored) == 1


class TestServeKeyGenFailure:
    """Failure path — never serve open: any key-gen error must abort serve with non-zero exit."""

    def test_key_gen_failure_aborts_with_clear_error(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """If generate_api_key() raises, _cmd_serve exits non-zero and does not call create_app."""
        parser = _build_parser()
        args = parser.parse_args(["serve", "--outdir", str(tmp_path)])

        def _boom() -> str:
            raise RuntimeError("entropy source unavailable")

        mock_app = MagicMock()
        mock_uvicorn = MagicMock()
        monkeypatch.setitem(sys.modules, "uvicorn", mock_uvicorn)

        with (
            patch("osimflow.api.create_app", return_value=mock_app) as mock_create,
            patch("osimflow.api.generate_api_key", side_effect=_boom),
        ):
            result = _cmd_serve(args)

        # Never serve open: non-zero exit, create_app never called, uvicorn never started.
        assert result == 1
        mock_create.assert_not_called()
        mock_uvicorn.run.assert_not_called()
        captured = capsys.readouterr()
        assert "failed to auto-generate API key" in captured.err
        assert "entropy source unavailable" in captured.err
        # The instruction must guide the operator to the explicit override.
        assert "--api-key" in captured.err


class TestServeHelpText:
    """The serve --help text must mention the new auto-gen behaviour (issue #1553)."""

    def test_help_mentions_autogen(self, capsys: pytest.CaptureFixture[str]) -> None:
        parser = _build_parser()
        with pytest.raises(SystemExit) as exc_info:
            parser.parse_args(["serve", "--help"])
        assert exc_info.value.code == 0
        captured = capsys.readouterr()
        # The --api-key help text must reference the auto-gen + issue #1553.
        assert "1553" in captured.out
        assert "ephemeral" in captured.out.lower() or "auto-generat" in captured.out.lower()
